-- سجل دخول وخروج أصحاب الصيدليات
-- شغّل هذا الملف مرة واحدة في Supabase > SQL Editor.

CREATE TABLE IF NOT EXISTS public.pharmacy_activity_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  pharmacy_id uuid NOT NULL REFERENCES public.pharmacies(id) ON DELETE CASCADE,
  event_type text NOT NULL CHECK (event_type IN ('entered','exited')),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS pharmacy_activity_events_created_at_idx
ON public.pharmacy_activity_events (created_at DESC);

ALTER TABLE public.pharmacy_activity_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.pharmacy_activity_events FROM anon, authenticated;

CREATE OR REPLACE FUNCTION public.log_pharmacy_activity(p_event_type text)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_pharmacy_id uuid;
BEGIN
  IF p_event_type NOT IN ('entered','exited') THEN
    RAISE EXCEPTION 'نوع حركة غير صالح';
  END IF;

  SELECT pharmacy_id INTO v_pharmacy_id
  FROM public.profiles
  WHERE user_id = auth.uid()
    AND pharmacy_id IS NOT NULL
    AND role <> 'admin';

  IF v_pharmacy_id IS NULL THEN
    RAISE EXCEPTION 'لا يوجد حساب صيدلية مرتبط بهذا المستخدم';
  END IF;

  INSERT INTO public.pharmacy_activity_events(user_id, pharmacy_id, event_type)
  VALUES (auth.uid(), v_pharmacy_id, p_event_type);
END;
$$;

REVOKE ALL ON FUNCTION public.log_pharmacy_activity(text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.log_pharmacy_activity(text) TO authenticated;

CREATE OR REPLACE FUNCTION public.get_admin_pharmacy_activity()
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_result jsonb;
BEGIN
  IF NOT public.is_admin() THEN
    RAISE EXCEPTION 'غير مصرح';
  END IF;

  SELECT COALESCE(jsonb_agg(row_to_json(x) ORDER BY x.event_time DESC), '[]'::jsonb)
  INTO v_result
  FROM (
    SELECT
      e.id,
      e.event_type,
      CASE WHEN e.event_type = 'entered' THEN 'دخول' ELSE 'خروج' END AS event_label,
      e.created_at AS event_time,
      p.name AS pharmacy_name,
      COALESCE(NULLIF(p.pharmacist_name,''), p.name) AS owner_name
    FROM public.pharmacy_activity_events e
    JOIN public.pharmacies p ON p.id = e.pharmacy_id
    ORDER BY e.created_at DESC
    LIMIT 100
  ) x;

  RETURN v_result;
END;
$$;

REVOKE ALL ON FUNCTION public.get_admin_pharmacy_activity() FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.get_admin_pharmacy_activity() TO authenticated;
